import type { InjectedMarketContext } from "../glass/data-injector.js";

export interface LocationPageInput {
  city: string;
  clientName: string;
  schemaMarkup: Record<string, unknown>;
  market: InjectedMarketContext;
}

export function renderLocationPageTemplate(input: LocationPageInput): string {
  const componentName = `${input.city.replace(/[^a-zA-Z0-9]/g, "")}LocationPage`;
  const schemaJson = JSON.stringify(input.schemaMarkup, null, 2);

  return `// Generated by SIGNAL\nconst schemaMarkup = ${schemaJson};\n\nexport const ${componentName} = () => (\n  <article className="max-w-4xl mx-auto px-4 py-12">\n    <h1 className="text-4xl font-bold mb-6">${input.clientName} in ${input.city}, MA</h1>\n    <p className="mb-4">${input.market.competitorPriceSummary}</p>\n    <p className="mb-4">${input.market.productAvailabilitySummary}</p>\n    <p className="mb-6">${input.market.marketPositionSummary}</p>\n    <script type="application/ld+json">{JSON.stringify(schemaMarkup)}</script>\n  </article>\n);\n`;
}
