export interface MarketReportInput {
  title: string;
  summary: string;
  schemaMarkup: Record<string, unknown>;
}

export function renderMarketReportTemplate(input: MarketReportInput): string {
  const schemaJson = JSON.stringify(input.schemaMarkup, null, 2);
  return `// Generated by SIGNAL\nconst schemaMarkup = ${schemaJson};\n\nexport const MarketReport = () => (\n  <article className="max-w-4xl mx-auto px-4 py-12">\n    <h1 className="text-4xl font-bold mb-6">${input.title}</h1>\n    <p className="mb-6">${input.summary}</p>\n    <script type="application/ld+json">{JSON.stringify(schemaMarkup)}</script>\n  </article>\n);\n`;
}
