export interface ProductPageInput {
  category: string;
  clientName: string;
  schemaMarkup: Record<string, unknown>;
  body: string;
}

export function renderProductPageTemplate(input: ProductPageInput): string {
  const componentName = `${input.category.replace(/[^a-zA-Z0-9]/g, "")}ProductPage`;
  const schemaJson = JSON.stringify(input.schemaMarkup, null, 2);

  return `// Generated by SIGNAL\nconst schemaMarkup = ${schemaJson};\n\nexport const ${componentName} = () => (\n  <article className="max-w-4xl mx-auto px-4 py-12">\n    <h1 className="text-4xl font-bold mb-6">${input.clientName} ${input.category} Guide</h1>\n    <p className="mb-6">${input.body}</p>\n    <script type="application/ld+json">{JSON.stringify(schemaMarkup)}</script>\n  </article>\n);\n`;
}
