/**
 * Generate FAQ Q&A pairs — either from the keyword brief or via LLM.
 */
async function generateFAQs(
  config: ClientConfig,
  contentType: ContentType,
  target: string,
  research: ResearchContext
): Promise<FAQItem[]> {
  const questions = research.keywordBrief.faqQuestions;
  if (questions.length === 0) {
    return [];
  }

  // Use LLM to generate answers for the FAQ questions
  const hasLLM = process.env.OPENAI_API_KEY || process.env.NVIDIA_API_KEY;
  if (!hasLLM) {
    // Fallback: return questions with generic answers
    return questions.slice(0, 5).map((q) => ({
      question: q,
      answer: `Please visit ${config.client.name} or call us for the most current information about this topic.`,
    }));
  }

  try {
    const market = injectGlassData(research.prices, research.products, research.operators);
    const systemPrompt = `You are a helpful cannabis dispensary expert answering customer questions for ${config.client.name} in Massachusetts. Give specific, factual answers. Mention 21+ age requirement where relevant. Never make health claims. Respond in valid JSON array format only.`;

    const userPrompt = `Answer these FAQ questions as JSON. Each answer should be 2-3 sentences, specific and helpful.

Market context:
- Average price: $${market.stats.overallAvgPrice.toFixed(2)}
- ${market.stats.totalProducts} products in stock across ${market.stats.categoryCount} categories
- Location: Near Logan Airport, East Boston, MA

Questions:
${questions.map((q, i) => `${i + 1}. ${q}`).join("\n")}

Return a JSON array: [{"question": "...", "answer": "..."}]`;

    const response = await generateContent(systemPrompt, userPrompt);
    const jsonMatch = response.match(/\[[\s\S]*\]/);
    if (jsonMatch?.[0]) {
      const parsed = JSON.parse(jsonMatch[0]) as Array<{ question: string; answer: string }>;
      return parsed
        .filter((item) => typeof item.question === "string" && typeof item.answer === "string")
        .slice(0, 7)
        .map((item) => ({ question: item.question, answer: item.answer }));
    }
  } catch {
    // Fall through to fallback
  }

  return questions.slice(0, 5).map((q) => ({
    question: q,
    answer: `Contact ${config.client.name} directly for the latest information. We're happy to help!`,
  }));
}

export async function runGenerate(input: GenerateInput): Promise<{ outputPath: string; content: string }> {
  const slugPart = (input.target ?? input.category ?? input.topic ?? input.type).toLowerCase().replace(/\s+/g, "-");
  const outputDir = path.resolve(process.cwd(), "output", input.config.client.slug);
  await mkdir(outputDir, { recursive: true });

  const market = injectGlassData(
    input.research.prices,
    input.research.products,
    input.research.operators,
    input.target ?? "the area"
  );

  // Build internal links and breadcrumbs
  const topicCluster = buildTopicCluster(input.config, input.type, slugPart);
  const breadcrumbs = buildBreadcrumbs(input.config, input.type, slugPart);

  // Generate FAQs
  const faqs = await generateFAQs(input.config, input.type, slugPart, input.research);
  const faqSchema = generateFAQSchema(faqs);
  const breadcrumbSchema = generateBreadcrumbSchema(
    breadcrumbs.map((b) => ({ name: b.text, url: b.href }))
  );

  let content = "";

  if (input.type === "location-page") {
    const city = input.target ?? "East Boston";
    const generatedBody = await generateLocationContent(input.config, city, input.research);

    const meta = generateMeta({
      keyword: input.research.keywordBrief.primaryKeyword,
      location: city,
      clientName: input.config.client.name,
      contentType: input.type,
      domain: input.config.client.domain,
      slug: slugPart,
    });

    const schemaMarkup = generateLocalBusinessSchema({
      name: input.config.client.name,
      description: `Cannabis dispensary in ${city}, Massachusetts. Browse our selection of flower, edibles, pre-rolls, vapes, and more.`,
      url: `https://${input.config.client.domain}/locations/${slugPart}`,
      areaServed: city,
      address: {
        streetAddress: "",
        addressLocality: city,
        addressRegion: "MA",
        postalCode: "",
        addressCountry: "US",
      },
      priceRange: market.stats.overallAvgPrice > 0
        ? `$${market.stats.lowestPrice.toFixed(0)}-$${market.stats.highestPrice.toFixed(0)}`
        : "$$",
    });

    content = renderLocationPageTemplate({
      city,
      state: "MA",
      clientName: input.config.client.name,
      generatedBody,
      schemaMarkup,
      faqSchema,
      breadcrumbSchema,
      market,
      faqs,
      internalLinks: topicCluster.spokePages,
      breadcrumbs,
      meta,
    });
  } else if (input.type === "product-page") {
    const category = input.category ?? "flower";
    const generatedBody = await generateProductContent(input.config, category, input.research);
    const categoryData = market.categoryPriceBreakdown.find(
      (c) => c.category.toLowerCase() === category.toLowerCase()
    );
    const categoryProducts = market.featuredProducts.filter(
      (p) => p.category.toLowerCase() === category.toLowerCase()
    );

    const meta = generateMeta({
      keyword: `${category} cannabis products`,
      location: input.target,
      clientName: input.config.client.name,
      contentType: input.type,
      domain: input.config.client.domain,
      slug: slugPart,
    });

    const schemaMarkup = generateProductSchema({
      name: `${input.config.client.name} ${category}`,
      description: `Browse ${category} products at ${input.config.client.name}. Current selection with live pricing.`,
      brand: input.config.client.name,
      category,
      price: categoryData?.avgPrice,
      priceCurrency: "USD",
      availability: "InStock",
    });

    content = renderProductPageTemplate({
      category,
      clientName: input.config.client.name,
      generatedBody,
      schemaMarkup,
      faqSchema,
      breadcrumbSchema,
      products: categoryProducts.length > 0 ? categoryProducts : market.featuredProducts.slice(0, 6),
      faqs,
      internalLinks: topicCluster.spokePages,
      breadcrumbs,
      meta,
      avgPrice: categoryData?.avgPrice ?? market.stats.overallAvgPrice,
      priceRange: categoryData
        ? `$${categoryData.minPrice.toFixed(2)} – $${categoryData.maxPrice.toFixed(2)}`
        : `$${market.stats.lowestPrice.toFixed(2)} – $${market.stats.highestPrice.toFixed(2)}`,
    });
  } else if (input.type === "market-report") {
    const city = input.target ?? "East Boston";
    const generatedBody = await generateMarketReportContent(input.config, city, input.research);
    const now = new Date().toISOString().split("T")[0] ?? "";

    const meta = generateMeta({
      keyword: `${city} cannabis market report`,
      clientName: input.config.client.name,
      contentType: input.type,
      domain: input.config.client.domain,
      slug: slugPart,
    });

    const schemaMarkup = generateArticleSchema({
      headline: `${input.config.client.name} ${city} Weekly Market Report`,
      description: `Weekly cannabis market analysis for ${city}, MA with pricing data and competitive insights.`,
      author: `${input.config.client.name} Market Intelligence`,
      publisher: input.config.client.name,
      datePublished: now,
      dateModified: now,
      url: `https://${input.config.client.domain}/market-reports/${slugPart}`,
    });

    content = renderMarketReportTemplate({
      title: `${city} Cannabis Market Report — Week of ${now}`,
      generatedBody,
      schemaMarkup,
      breadcrumbSchema,
      categoryBreakdown: market.categoryPriceBreakdown,
      competitors: market.competitorComparisons,
      internalLinks: topicCluster.spokePages,
      breadcrumbs,
      meta,
      clientName: input.config.client.name,
      city,
      reportDate: now,
    });
  } else {
    const topic = input.topic ?? "airport cannabis guide";
    const generatedBody = await generateBlogContent(input.config, topic, input.research);
    const now = new Date().toISOString().split("T")[0] ?? "";

    const meta = generateMeta({
      keyword: topic,
      location: input.target,
      clientName: input.config.client.name,
      contentType: input.type,
      domain: input.config.client.domain,
      slug: slugPart,
    });

    const schemaMarkup = generateArticleSchema({
      headline: `${input.config.client.name}: ${topic}`,
      description: `${topic} — a guide from ${input.config.client.name}.`,
      author: `${input.config.client.name} Team`,
      publisher: input.config.client.name,
      datePublished: now,
      dateModified: now,
      url: `https://${input.config.client.domain}/blog/${slugPart}`,
    });

    content = renderBlogPostTemplate({
      title: `${input.config.client.name}: ${topic}`,
      topic,
      generatedBody,
      schemaMarkup,
      faqSchema,
      breadcrumbSchema,
      faqs,
      internalLinks: topicCluster.spokePages,
      breadcrumbs,
      meta,
      clientName: input.config.client.name,
      publishDate: now,
      author: `${input.config.client.name} Team`,
    });
  }

  const outputPath = path.join(outputDir, `${input.type}-${slugPart}.tsx`);
  await writeFile(outputPath, content, "utf-8");

  return { outputPath, content };
}
