export type ContentType = "location-page" | "product-page" | "market-report" | "blog-post";

export interface GenerateInput {
  config: ClientConfig;
  type: ContentType;
  target?: string;
  category?: string;
  topic?: string;
  research: ResearchContext;
}

/**
 * Build the LLM system prompt for content generation.
 */
function buildSystemPrompt(config: ClientConfig, contentType: ContentType): string {
  return `You are an expert cannabis industry content writer for ${config.client.name}, a Massachusetts dispensary. You write SEO-optimized content for their website.

WRITING RULES:
- Write in HTML paragraph and heading tags (<p>, <h2>, <h3>) — this goes inside a React JSX template
- Use <h2> for main sections and <h3> for subsections
- Write 1,500-2,000 words for location/blog/report pages, 800-1,200 words for product pages
- Include specific details, prices, and product names from the data provided
- Sound like a knowledgeable local — welcoming but not salesy
- Audience: ${config.audience.primary}
- Tone: ${config.tone.voice}
- AVOID: ${config.tone.avoid.join(", ")}
- Include Massachusetts cannabis regulations where relevant (21+ age requirement, valid ID, possession limits)
- Use className for CSS classes (this is JSX, not HTML)
- Do NOT include <h1> tags (that's handled by the template)
- Do NOT include <article>, <script>, or wrapper elements
- Do NOT include "Generated by" watermarks
- Use straight quotes, not curly quotes
- Keep paragraphs varied in length — mix short and long
- Be specific: use actual product names, prices, and data from the context provided

CANNABIS COMPLIANCE (935 CMR 500):
- Never make health claims (no "cures", "treats", "heals")
- Never target minors
- Always mention 21+ age requirement when discussing purchasing
- No claims about FDA approval
- Do not guarantee effects`;
}

/**
 * Generate location page content via LLM.
 */
async function generateLocationContent(
  config: ClientConfig,
  city: string,
  research: ResearchContext
): Promise<string> {
  const market = injectGlassData(research.prices, research.products, research.operators, city);
  const brief = research.keywordBrief;

  const userPrompt = `Write the body content for a location page about ${config.client.name} in ${city}, Massachusetts.

TARGET KEYWORD: "${brief.primaryKeyword}"
SECONDARY KEYWORDS: ${brief.secondaryKeywords.join(", ")}
SEARCH INTENT: ${brief.searchIntent}

MARKET DATA FROM GLASS:
- ${market.stats.totalOperators} dispensaries tracked in ${city}
- ${market.stats.totalProducts} products tracked, ${market.stats.inStockCount} currently in stock
- Overall average price: $${market.stats.overallAvgPrice.toFixed(2)}
- Price range: $${market.stats.lowestPrice.toFixed(2)} to $${market.stats.highestPrice.toFixed(2)}
- Categories: ${market.categoryPriceBreakdown.map((c) => `${c.category} (avg $${c.avgPrice.toFixed(2)}, ${c.productCount} products)`).join(", ")}
- Top products: ${market.featuredProducts.map((p) => `${p.name} ($${p.price.toFixed(2)})`).join(", ")}
- Competitors: ${market.competitorComparisons.map((c) => `${c.operatorName} (avg $${c.avgPrice.toFixed(2)}, ${c.productCount} products)`).join(", ")}

REQUIRED SECTIONS (use <h2> for each):
${brief.suggestedSections.map((s) => `- ${s}`).join("\n")}

Also include:
- Getting here / directions context (${city} is near Logan Airport)
- What first-time visitors should know (ID requirements, MA cannabis laws)
- Neighborhood context — what's nearby, parking, public transit
- A "What We Carry" overview referencing the actual product categories and prices above

Write approximately 1,500-2,000 words. Use the actual data provided — reference specific prices, product counts, and competitor names.`;

  return generateContent(buildSystemPrompt(config, "location-page"), userPrompt);
}

/**
 * Generate product page content via LLM.
 */
async function generateProductContent(
  config: ClientConfig,
  category: string,
  research: ResearchContext
): Promise<string> {
  const market = injectGlassData(research.prices, research.products, research.operators);
  const categoryProducts = market.featuredProducts.filter(
    (p) => p.category.toLowerCase() === category.toLowerCase()
  );
  const categoryData = market.categoryPriceBreakdown.find(
    (c) => c.category.toLowerCase() === category.toLowerCase()
  );
  const brief = research.keywordBrief;

  const userPrompt = `Write the body content for a product category page about ${category} at ${config.client.name}.

TARGET KEYWORD: "${brief.primaryKeyword}"
SECONDARY KEYWORDS: ${brief.secondaryKeywords.join(", ")}

PRODUCT DATA:
- Category: ${category}
- Average price: ${categoryData ? `$${categoryData.avgPrice.toFixed(2)}` : "varies"}
- Price range: ${categoryData ? `$${categoryData.minPrice.toFixed(2)} – $${categoryData.maxPrice.toFixed(2)}` : "varies"}
- Available products: ${categoryProducts.map((p) => `${p.name} ($${p.price.toFixed(2)})`).join(", ") || "see our current menu"}
- Total in category: ${categoryData?.productCount ?? "multiple"} products

REQUIRED SECTIONS (use <h2> for each):
- What is ${category}? (for newcomers)
- Our ${category} selection (reference specific products and prices)
- How to choose the right ${category} product
- ${category} pricing at ${config.client.name}
- Tips for first-time buyers
- Storage and usage guidelines

Write approximately 800-1,200 words. Reference the actual products and prices above. Include Massachusetts purchase requirements (21+, valid ID).`;

  return generateContent(buildSystemPrompt(config, "product-page"), userPrompt);
}

/**
 * Generate market report content via LLM.
 */
async function generateMarketReportContent(
  config: ClientConfig,
  city: string,
  research: ResearchContext
): Promise<string> {
  const market = injectGlassData(research.prices, research.products, research.operators, city);

  const userPrompt = `Write a weekly cannabis market report for the ${city}, Massachusetts area.

MARKET DATA:
- ${market.stats.totalOperators} dispensaries tracked
- ${market.stats.totalProducts} products across ${market.stats.categoryCount} categories
- ${market.stats.inStockCount} currently in stock (${Math.round((market.stats.inStockCount / Math.max(market.stats.totalProducts, 1)) * 100)}% availability)
- Overall average price: $${market.stats.overallAvgPrice.toFixed(2)}
- Category breakdown: ${market.categoryPriceBreakdown.map((c) => `${c.category}: avg $${c.avgPrice.toFixed(2)} (${c.productCount} products, range $${c.minPrice.toFixed(2)}-$${c.maxPrice.toFixed(2)})`).join("; ")}
- Competitors: ${market.competitorComparisons.map((c) => `${c.operatorName}: avg $${c.avgPrice.toFixed(2)}, ${c.productCount} products, strongest in ${c.categoryStrength}`).join("; ")}

REQUIRED SECTIONS (use <h2> for each):
- Market overview and key trends
- Pricing analysis by category
- Inventory and availability update
- Competitive landscape
- What this means for consumers
- Outlook and what to watch

Write approximately 1,500-2,000 words. This should read as authoritative market analysis, not marketing copy. Use the specific data above — cite actual numbers, compare competitors by name, and highlight notable trends.`;

  return generateContent(buildSystemPrompt(config, "market-report"), userPrompt);
}

/**
 * Generate blog post content via LLM.
 */
