import { humanizeContent } from "../llm/openai-client.js";

/**
 * LLM-based content humanizer.
 *
 * Sends generated content through a rewriting pass that:
 * - Removes AI writing patterns (per humanizer skill patterns)
 * - Injects natural voice variation
 * - Applies brand voice from config
 * - Strips watermarks and robotic phrases
 * - Varies sentence structure and length
 *
 * Falls back to rule-based humanization if no API key is available.
 */

const HUMANIZER_SYSTEM_PROMPT = `You are a professional editor specializing in making AI-generated content sound natural and human-written. You work for a cannabis dispensary marketing team.

Your job: rewrite the provided content to remove ALL signs of AI generation while keeping the meaning, structure, and SEO elements intact.

CRITICAL RULES:
1. PRESERVE all HTML/JSX tags exactly as they are. Do not add, remove, or modify any HTML tags, React components, className attributes, or JSX syntax.
2. PRESERVE all JSON-LD schema blocks exactly. Do not touch anything inside <script type="application/ld+json"> blocks.
3. PRESERVE all JavaScript/TypeScript code (const declarations, export statements, import statements, variable assignments).
4. ONLY rewrite the human-readable text content BETWEEN the HTML tags.
5. Remove any "Generated by SIGNAL" or similar watermark comments.

AI PATTERNS TO FIX (from Wikipedia's "Signs of AI writing"):
- Remove "Additionally", "Moreover", "Furthermore" — use natural transitions or just start the sentence
- Replace "crucial", "pivotal", "vibrant", "tapestry", "landscape" (figurative), "delve", "foster", "garner", "underscore", "showcase", "testament" with plain language
- Break up Rule of Three patterns (things don't always come in threes)
- Remove em dash overuse — use commas, periods, or parentheses instead
- Kill "It's not just X, it's Y" negative parallelism constructions
- Remove "-ing" superficial analysis phrases ("highlighting...", "showcasing...", "emphasizing...")
- Replace "serves as" / "stands as" with "is"
- Remove sycophantic language ("Great question!", "Certainly!")
- Add personality: vary sentence length, have opinions where appropriate, be specific instead of vague
- Use "is/are/has" instead of "serves as/boasts/features"
- Remove hedging ("It could potentially possibly be argued that...")
- Remove generic positive conclusions ("The future looks bright...")
- Use straight quotes, not curly quotes

VOICE GUIDELINES:
- Sound like a knowledgeable local, not a corporate brochure
- Short sentences mixed with longer ones
- Be direct and specific
- Use first-person plural ("we", "our") when referring to the business
- Reference specific details rather than vague claims
- It's okay to be informal — this is a dispensary, not a law firm

Return ONLY the rewritten content. No explanations, no commentary, no meta-text.`;

/**
 * Rule-based fallback humanizer for when LLM is unavailable.
 * Applies the most common AI pattern fixes mechanically.
 */
function ruleBasedHumanize(content: string): string {
  let result = content;

  // Remove SIGNAL watermarks
  result = result.replace(/\/\/\s*Generated by SIGNAL[^\n]*/g, "");
  result = result.replace(/Generated by SIGNAL[^"]*/g, "");

  // Replace overused AI transition words (only in text content, not in tags)
  const aiWords: [RegExp, string][] = [
    [/\bAdditionally,\s/g, ""],
    [/\bMoreover,\s/g, ""],
    [/\bFurthermore,\s/g, ""],
    [/\bIt is important to note that\s/g, ""],
    [/\bIt is worth noting that\s/g, ""],
    [/\bIn order to\s/g, "To "],
    [/\bDue to the fact that\s/g, "Because "],
    [/\bAt this point in time\b/g, "Now"],
    [/\bserves as a?\s/g, "is "],
    [/\bstands as a?\s/g, "is "],
    [/\bboasts a?\s/g, "has "],
    [/\ba testament to\b/g, "proof of"],
    [/\bthe evolving landscape of\b/g, "changes in"],
    [/\bin the heart of\b/g, "in"],
    [/\bnestled in\b/gi, "in"],
    [/\bvibrant\s+community\b/g, "community"],
    [/\brich\s+history\b/g, "history"],
    [/\bgroundbreaking\b/g, "new"],
  ];

  for (const [pattern, replacement] of aiWords) {
    result = result.replace(pattern, replacement);
  }

  // Clean up double spaces
  result = result.replace(/\s{2,}/g, " ");

  return result;
}

/**
 * Run the humanizer pipeline on generated content.
 * Uses LLM-based rewriting when available, falls back to rule-based.
 */
export async function runHumanize(content: string, brandVoice?: string): Promise<string> {
  const apiKey = process.env.OPENAI_API_KEY;

  if (!apiKey) {
    console.warn("No OPENAI_API_KEY — using rule-based humanizer fallback.");
    return ruleBasedHumanize(content);
  }

  try {
    const voiceAddendum = brandVoice
      ? `\n\nBRAND VOICE: ${brandVoice}. Adapt the tone to match this voice while keeping it natural.`
      : "";

    const systemPrompt = HUMANIZER_SYSTEM_PROMPT + voiceAddendum;
    const result = await humanizeContent(systemPrompt, content);

    // Safety check: make sure the LLM didn't strip essential elements
    if (!result.includes("<article") && content.includes("<article")) {
      console.warn("Humanizer stripped JSX structure — falling back to rule-based.");
      return ruleBasedHumanize(content);
    }

    return result;
  } catch (error) {
    const reason = error instanceof Error ? error.message : "Unknown humanizer error";
    console.warn(`LLM humanizer failed (${reason}) — using rule-based fallback.`);
    return ruleBasedHumanize(content);
  }
}
